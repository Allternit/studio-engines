"""Adapter for Axolotl: writes its YAML config, runs `axolotl train` as a process."""

from __future__ import annotations

from pathlib import Path
from typing import Dict, List

from studio_engine_kit import yamlish
from studio_engine_kit.adapter import Adapter, Build, OutputSpec, Step, gguf_outputs, gguf_steps, require_llama_cpp
from studio_engine_kit.spec import Settings, SpecError

from ._common import linear_modules

CONFIG = "config/axolotl.yaml"
OUT = "out/train"
MERGED_LORA = "out/train/merged"

SFT_TYPE = {
    "jsonl": {"type": "alpaca"},
    "alpaca": {"type": "alpaca"},
    "chat": {"type": "chat_template", "field_messages": "messages"},
    "text": {"type": "completion"},
    "completion": {"type": "completion"},
}
DPO_TYPE = {"type": {"field_prompt": "prompt", "field_chosen": "chosen", "field_rejected": "rejected",
                     "prompt_format": "{prompt}", "chosen_format": "{chosen}", "rejected_format": "{rejected}"}}


class Axolotl(Adapter):
    id = "axolotl"
    pin = "0.21.1"
    executable = "axolotl"

    def check_spec(self, s: Settings) -> None:
        if s.dataset_path and s.dataset_revision:
            raise SpecError("invalid_dataset", "dataset.revision only applies to a dataset repo")

    def config(self, s: Settings) -> Dict:
        ds: Dict = {"path": s.dataset_path or s.dataset_repo}
        if s.dataset_path:
            ds["ds_type"] = "parquet" if s.dataset_path.endswith(".parquet") else "json"
        elif s.dataset_revision:
            ds["revision"] = s.dataset_revision
        ds.update(DPO_TYPE if s.method == "dpo" else SFT_TYPE[s.dataset_format])
        cfg: Dict = {"base_model": s.base}
        if s.method in ("lora", "dpo"):
            cfg["adapter"] = "lora"
        elif s.method == "qlora":
            cfg["adapter"] = "qlora"
            cfg["load_in_4bit"] = True
        if s.method == "dpo":
            cfg["rl"] = "dpo"
            cfg["dpo_beta"] = s.beta
        if s.method != "full":
            cfg["lora_r"] = s.rank
            cfg["lora_alpha"] = s.alpha
            cfg["lora_dropout"] = s.dropout
            if s.target_modules == "all-linear":
                cfg["lora_target_linear"] = True
            else:
                cfg["lora_target_modules"] = linear_modules(s)
        cfg.update({
            "sequence_len": s.max_seq_len,
            "sample_packing": False,
            "datasets": [ds],
            "output_dir": OUT,
            "num_epochs": s.epochs,
            "micro_batch_size": s.batch_size,
            "gradient_accumulation_steps": s.grad_accum,
            "learning_rate": s.lr,
            "lr_scheduler": s.lr_scheduler,
            "warmup_steps": s.warmup_steps,
            "weight_decay": s.weight_decay,
            "seed": s.seed,
            "gradient_checkpointing": s.gradient_checkpointing,
            "bf16": "auto",
            "logging_steps": 1,
        })
        if s.max_steps > 0:
            cfg["max_steps"] = s.max_steps
        return cfg

    def build(self, s: Settings, job_dir: Path) -> Build:
        exe = self.engine_command()
        steps: List[Step] = [Step("train", exe + ["train", CONFIG])]
        outputs: List[OutputSpec] = []
        merged_dir = OUT
        if s.method == "full":
            outputs.append(OutputSpec("merged", OUT))
        else:
            if s.want_adapter:
                outputs.append(OutputSpec("adapter", OUT + "/adapter_model.safetensors"))
            merged_dir = MERGED_LORA
            if s.want_merged or s.gguf:
                steps.append(Step("merge", exe + ["merge-lora", CONFIG, "--lora-model-dir", OUT]))
            if s.want_merged:
                outputs.append(OutputSpec("merged", MERGED_LORA))
        if s.gguf:
            steps += gguf_steps(merged_dir, s.gguf, "out/gguf", require_llama_cpp(s))
            outputs += gguf_outputs(s.gguf, "out/gguf")
        header = "# SPDX-License-Identifier: Apache-2.0\n# Generated by studio-engines (axolotl adapter)"
        return Build({CONFIG: yamlish.dump(self.config(s), header)}, steps, outputs)


ADAPTER = Axolotl()
