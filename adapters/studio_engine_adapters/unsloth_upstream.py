"""Adapter for upstream Unsloth, run UNMODIFIED as a separate process.

The adapter writes a YAML config and starts upstream's own `unsloth train
--config` and `unsloth export` commands. It never imports upstream code: the
only link between this Apache-2.0 file and the AGPL-3.0 engine is the command
line and the files on disk (see README, "Licences").
"""

from __future__ import annotations

from pathlib import Path
from typing import Dict, List

from studio_engine_kit import yamlish
from studio_engine_kit.adapter import Adapter, Build, OutputSpec, Step
from studio_engine_kit.spec import Settings, SpecError

from ._common import DEFAULT_LORA_LINEAR, linear_modules, refuse_revision, whole_epochs

CONFIG = "config/unsloth.yaml"
OUT = "out/train"

FORMAT_TYPE = {"jsonl": "auto", "alpaca": "alpaca", "chat": "conversational", "text": "raw", "completion": "raw"}


class UnslothUpstream(Adapter):
    id = "unsloth-upstream"
    pin = "2026.11.4"
    executable = "unsloth"
    # No DPO: upstream `unsloth train` has no preference-training option and DPO
    # would need code that imports the library, which this repo never does.
    # engines.json lists lora and qlora only, so a dpo spec is unknown_method.

    def check_spec(self, s: Settings) -> None:
        refuse_revision(s, "unsloth")
        if s.lr_scheduler != "linear":
            raise SpecError("invalid_spec", "params.lr_scheduler is not configurable in `unsloth train`")
        if s.dataset_format not in FORMAT_TYPE:
            raise SpecError("invalid_dataset", f"dataset.format {s.dataset_format} is not supported by unsloth")
        whole_epochs(s, "unsloth")

    def config(self, s: Settings) -> Dict:
        data: Dict = {"format_type": FORMAT_TYPE[s.dataset_format]}
        if s.dataset_path:
            data["local_dataset"] = [s.dataset_path]
        else:
            data["dataset"] = s.dataset_repo
        cfg: Dict = {
            "model": s.base,
            "data": data,
            "training": {
                "training_type": "full" if s.method == "full" else "lora",
                "max_seq_length": s.max_seq_len,
                "load_in_4bit": s.method == "qlora",
                "output_dir": OUT,
                "num_epochs": whole_epochs(s, "unsloth"),
                "learning_rate": s.lr,
                "batch_size": s.batch_size,
                "gradient_accumulation_steps": s.grad_accum,
                "warmup_steps": s.warmup_steps,
                "max_steps": max(s.max_steps, 0),
                "weight_decay": s.weight_decay,
                "random_seed": s.seed,
                "gradient_checkpointing": "unsloth" if s.gradient_checkpointing else "none",
            },
        }
        if s.method != "full":
            cfg["lora"] = {
                "lora_r": s.rank, "lora_alpha": s.alpha, "lora_dropout": s.dropout,
                "target_modules": ",".join(linear_modules(s)) if s.target_modules != "all-linear"
                else ",".join(DEFAULT_LORA_LINEAR),
            }
        return cfg

    def build(self, s: Settings, job_dir: Path) -> Build:
        exe = self.engine_command()
        steps: List[Step] = [Step("train", exe + ["train", "--config", CONFIG])]
        outputs: List[OutputSpec] = []
        if s.method == "full":
            outputs.append(OutputSpec("merged", OUT))
        else:
            if s.want_adapter:
                outputs.append(OutputSpec("adapter", OUT))
            if s.want_merged:
                steps.append(Step("merge", exe + ["export", OUT, "out/merged", "--format", "merged-16bit"]))
                outputs.append(OutputSpec("merged", "out/merged"))
        for q in s.gguf:
            steps.append(Step(f"gguf-{q}", exe + ["export", OUT, f"out/gguf/{q}", "--format", "gguf",
                                                   "--quantization", q]))
            outputs.append(OutputSpec("gguf", f"out/gguf/{q}/*.gguf"))
        header = "# SPDX-License-Identifier: Apache-2.0\n# Generated by studio-engines (unsloth-upstream adapter)"
        return Build({CONFIG: yamlish.dump(self.config(s), header)}, steps, outputs)


ADAPTER = UnslothUpstream()
