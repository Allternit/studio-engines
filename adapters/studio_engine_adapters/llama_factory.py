"""Adapter for LLaMA-Factory: YAML config + dataset_info.json, `llamafactory-cli`."""

from __future__ import annotations

import json
from pathlib import Path
from typing import Dict, List

from studio_engine_kit import yamlish
from studio_engine_kit.adapter import Adapter, Build, OutputSpec, Step, gguf_outputs, gguf_steps, require_llama_cpp
from studio_engine_kit.spec import Settings, SpecError

from ._common import linear_modules

CONFIG = "config/train.yaml"
MERGE = "config/merge.yaml"
DATASET_INFO = "config/dataset_info.json"
OUT = "out/train"
DATASET_NAME = "studio_train"

# (substring of the base name -> LLaMA-Factory chat template). First hit wins.
TEMPLATES = [("qwen", "qwen"), ("llama-3", "llama3"), ("llama3", "llama3"), ("mistral", "mistral"),
             ("gemma", "gemma"), ("phi-3", "phi"), ("phi3", "phi")]


def template_for(base: str) -> str:
    low = base.lower()
    for key, template in TEMPLATES:
        if key in low:
            return template
    return "default"


class LlamaFactory(Adapter):
    id = "llama-factory"
    pin = "0.9.5"
    executable = "llamafactory-cli"

    def check_spec(self, s: Settings) -> None:
        if s.dataset_revision:
            raise SpecError("invalid_dataset", "dataset.revision is not supported by LLaMA-Factory")

    def dataset_info(self, s: Settings) -> Dict:
        entry: Dict = {"file_name": s.dataset_path} if s.dataset_path else {"hf_hub_url": s.dataset_repo}
        fmt = s.dataset_format
        if s.method == "dpo":
            entry.update({"ranking": True, "formatting": "alpaca",
                          "columns": {"prompt": "prompt", "chosen": "chosen", "rejected": "rejected"}})
        elif fmt in ("alpaca", "jsonl"):
            entry["formatting"] = "alpaca"
        elif fmt == "chat":
            entry.update({"formatting": "sharegpt", "columns": {"messages": "messages"},
                          "tags": {"role_tag": "role", "content_tag": "content",
                                   "user_tag": "user", "assistant_tag": "assistant"}})
        else:  # text, completion: pre-training style, one text column
            entry["columns"] = {"prompt": "text"}
        return {DATASET_NAME: entry}

    def config(self, s: Settings) -> Dict:
        pretrain = s.dataset_format in ("text", "completion") and s.method != "dpo"
        cfg: Dict = {
            "model_name_or_path": s.base,
            "stage": "dpo" if s.method == "dpo" else ("pt" if pretrain else "sft"),
            "do_train": True,
            "finetuning_type": "full" if s.method == "full" else "lora",
        }
        if s.method == "qlora":
            cfg["quantization_bit"] = 4
            cfg["quantization_method"] = "bitsandbytes"
        if s.method != "full":
            cfg["lora_rank"] = s.rank
            cfg["lora_alpha"] = s.alpha
            cfg["lora_dropout"] = s.dropout
            cfg["lora_target"] = "all" if s.target_modules == "all-linear" else ",".join(linear_modules(s))
        if s.method == "dpo":
            cfg["pref_beta"] = s.beta
            cfg["pref_loss"] = "sigmoid"
        cfg.update({
            "dataset": DATASET_NAME, "dataset_dir": "config", "template": template_for(s.base),
            "cutoff_len": s.max_seq_len, "output_dir": OUT, "overwrite_output_dir": True,
            "per_device_train_batch_size": s.batch_size, "gradient_accumulation_steps": s.grad_accum,
            "learning_rate": s.lr, "num_train_epochs": s.epochs, "lr_scheduler_type": s.lr_scheduler,
            "warmup_steps": s.warmup_steps, "weight_decay": s.weight_decay, "seed": s.seed,
            "gradient_checkpointing": s.gradient_checkpointing,
            "bf16": True, "logging_steps": 1, "save_steps": 500, "plot_loss": False, "report_to": "none",
        })
        if s.max_steps > 0:
            cfg["max_steps"] = s.max_steps
        return cfg

    def merge_config(self, s: Settings) -> Dict:
        return {"model_name_or_path": s.base, "adapter_name_or_path": OUT, "template": template_for(s.base),
                "finetuning_type": "lora", "export_dir": "out/merged", "export_size": 5,
                "export_device": "cpu", "export_legacy_format": False}

    def build(self, s: Settings, job_dir: Path) -> Build:
        exe = self.engine_command()
        header = "# SPDX-License-Identifier: Apache-2.0\n# Generated by studio-engines (llama-factory adapter)"
        files = {CONFIG: yamlish.dump(self.config(s), header),
                 DATASET_INFO: json.dumps(self.dataset_info(s), indent=2) + "\n"}
        steps: List[Step] = [Step("train", exe + ["train", CONFIG])]
        outputs: List[OutputSpec] = []
        merged_dir = OUT
        if s.method == "full":
            outputs.append(OutputSpec("merged", OUT))
        else:
            if s.want_adapter:
                outputs.append(OutputSpec("adapter", OUT + "/adapter_model.safetensors"))
            merged_dir = "out/merged"
            if s.want_merged or s.gguf:
                files[MERGE] = yamlish.dump(self.merge_config(s), header)
                steps.append(Step("merge", exe + ["export", MERGE]))
            if s.want_merged:
                outputs.append(OutputSpec("merged", "out/merged"))
        if s.gguf:
            steps += gguf_steps(merged_dir, s.gguf, "out/gguf", require_llama_cpp(s))
            outputs += gguf_outputs(s.gguf, "out/gguf")
        return Build(files, steps, outputs)


ADAPTER = LlamaFactory()
